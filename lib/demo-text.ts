import type { GenerateTask, Project } from "./types";

function titleOf(project: Project): string {
  return project.title.trim() || "未命名";
}

export function demoText(
  task: GenerateTask,
  project: Project,
  extra?: { readerName?: string; feedback?: string },
): string {
  const title = titleOf(project);
  if (task === "outline") return outline(title);
  if (task === "draft") return draft(title);
  if (task === "polish") return polish(title);
  if (task === "quality-check") return quality(project);
  if (task === "review") return review(extra?.readerName || "读者", title);
  if (task === "amend-review") return amendedReview(extra?.readerName || "读者", extra?.feedback || "");
  return revised(title, extra?.feedback || "意见");
}

function outline(title: string): string {
  return `# ${title}

> 演示占位。未调用模型。

## 人物（仅成年人）
沈酌，34 岁，前文学杂志编辑，现居城南，靠给出版社看外稿过活。想把一封没回的信说完，软肋是习惯用改稿代替道歉。
梁照，41 岁，已出版过两部长篇的小说作者。想拿回被沈酌压了三年的手稿，软肋是把未写完的书当成还没结束的关系。
两人曾经是恋人，分开时都已成年。

## 核心冲突
梁照在雨夜把修订过的旧稿放到沈酌门口。沈酌必须在当晚决定：把稿子退回，还是承认自己压着它，是因为舍不得把关系改成普通的编辑与作者。

## 本节节拍
1. 城南出租屋，雨。沈酌听见楼梯上有人放下纸袋就离开。他打开，看见自己三年前用红笔改过的第一章，页边是梁照新写的批注。
2. 沈酌没有追下楼。他烧水，逐页看批注。梁照保留了他几乎全部的删改，只在结尾加了一句对白。水壶响了，他起身关掉火。
3. 对白写明两人分开时沈酌 31 岁、梁照 38 岁。沈酌意识到自己一直用「当时还年轻」掩饰。
4. 他给梁照发这栋楼的地址。写下之前，他用红笔在铅笔句子旁边留了一指宽，写「删掉那句太年轻」。楼下引擎声熄了又响。节拍停在门把手转动之前。

## 必须出现的细节
红笔、铅笔批注「别写成年少」、关掉的水壶、门牌地址、34 岁与 41 岁。

## 文风与尺度
第三人称，贴沈酌。句子短。情欲只作为两个成年人的旧关系余温，不替代「稿子是否归还」。

## 待定
演示稿把人物暂定为沈酌与梁照。真实生成时会按你的想法重写，并保持角色成年。`;
}

function draft(title: string): string {
  return `雨先打在自行车棚上。沈酌把红笔搁进笔洗，才听见纸袋碰在门外，很轻。

他三十四岁，在城南这间房子里住了第七年。杂志停了以后，他靠看外稿过日子。今晚这一袋不是约稿。牛皮纸边角是他当年贴的，封面上梁照的名字被雨水洇开了一点。梁照今年四十一。完整的稿子上次留给他，是三年前的秋天。

他没有追下楼。水壶响了一声，他过去把火关掉，又坐回灯下，从第一页看。自己的红笔大多还在。梁照几乎都留下了。只在这一节最后，她用铅笔加了一行。

「我们分开的时候，你三十一，我三十八。别写成年少。」

沈酌没有把这行抄进自己的笔记本。他拿起红笔，在旁边空了一指宽的地方写：「删掉那句太年轻。」写完才发现，三年前那封没发出的退稿信里，他用过的就是这个借口。

他给梁照发了这栋楼的地址。楼下引擎熄了一会儿。他没有把那页纸翻过去。

【本节完】

> 演示占位。《${title}》的这一节只为把初稿走通。真实生成会按目标字数写满节拍。`;
}

function polish(title: string): string {
  return `雨先打在自行车棚上。沈酌把红笔搁进笔洗，才听见纸袋碰在门外。

他三十四岁，在城南住了第七年，靠看外稿过日子。牛皮纸边角是他当年贴的。封面上梁照的名字被雨水洇开了一点。梁照今年四十一。完整的稿子上次留给他，是三年前的秋天。

他没有追下楼。水壶响了一声，他起身关掉火，坐回灯下从第一页看。自己的红笔大多还在。只在这一节最后，梁照用铅笔加了一行：「我们分开的时候，你三十一，我三十八。别写成年少。」

沈酌拿起红笔，在旁边空了一指宽的地方写：「删掉那句太年轻。」写完他才承认，三年前那封没发出的退稿信里，用的就是这个借口。

他把这栋楼的地址发给梁照。楼下引擎熄了一会儿。那页纸还摊开着。

【本节完】

## 改动说明
- 演示润色：水壶有关掉的动作，铅笔句子留在他坐定之后。
- 年龄与三年前的数字保持不变。

> 演示占位。《${title}》。`;
}

function quality(project: Project): string {
  const target = project.wordMin && project.wordMax ? `${project.wordMin}–${project.wordMax}` : "2000–3500";
  return `## 字数
演示质检。相对目标 ${target}（不计空白），当前正文明显偏短，差了一整段可以展开的夜谈。

## 贴大纲
1. 纸袋放到门口：写到了。
2. 烧水、看批注、关火：写到了。
3. 年龄对白：写到了。
4. 发地址、红笔回应：写到了。门把手之前的停留偏薄，只点了一下引擎声。

## 细节缺口
未发现缺掉「别写成年少」。门牌若大纲要求写进正文，这里只说了「这栋楼的地址」，没有门牌数字。

## 可执行改法
1. 在发地址之前加一个具体动作：他看了眼门牌，再把数字打进消息。
2. 引擎熄了之后补两句他没有下楼的身体动作，不要解释主题。
3. 不要把人物写小。

> 演示占位。未调用模型。`;
}

function review(name: string, title: string): string {
  return `## ${name}
这是演示意见，不是模型写的。材料是《${title}》。

## 戳中或追读
年龄写明了，34 岁和 41 岁，红笔比拥抱更像把柄。

## 问题
雨和引擎声还是多。若这是大纲，节拍够写；若这是正文，字数偏短，第四拍停得太快。

## 一句改法
让沈酌在发送地址之前对那行铅笔对白做一个具体动作：留下，或用红笔划掉。

> 演示占位。`;
}

function amendedReview(name: string, discussion: string): string {
  const talk = discussion.replace(/\s+/g, " ").trim().slice(0, 80);
  return `## ${name}
按讨论改过的演示意见。${talk ? `作者要改的是：${talk}` : "作者没有写下具体句子。"}

## 一句改法
把被点名的那一拍写成具体动作。其余仍按这位读者原来的立场，不改成作者的旁白。

> 演示占位。`;
}

function revised(title: string, feedback: string): string {
  return `雨先打在自行车棚上。沈酌把红笔搁进笔洗，才听见纸袋碰在门外。

他三十四岁。梁照今年四十一。三年前的秋天，完整的稿子留在他这里。水壶响过一声，他已经把火关掉。

铅笔那行还在：「我们分开的时候，你三十一，我三十八。别写成年少。」他用红笔在旁边写下：「删掉那句太年轻。」然后才把地址发出去。

【本节完】

## 改动说明
- 演示改稿，意见摘要：${feedback}
- 未改掉已写明的成年年龄。

> 演示占位。《${title}》。`;
}
